#!/usr/bin/env bash
# Render /etc/uzex/agent.env from AWS SSM Parameter Store.
#
# Run this ON the EC2 host, as root, with an instance profile that can read
#   /uzex/prod/*
#
# Secrets are read with --with-decryption and written directly into a
# root-only file. No value is printed to stdout, a log or a shell history.
#
# Usage:
#   sudo AWS_REGION=<region> bash deploy/aws/render-env.sh
set -euo pipefail

REGION="${AWS_REGION:-}"
if [[ -z "$REGION" ]]; then
  echo "ERROR: set AWS_REGION" >&2
  exit 1
fi

if ! command -v aws >/dev/null 2>&1; then
  echo "ERROR: AWS CLI is not installed" >&2
  exit 1
fi

TARGET_DIR="/etc/uzex"
TARGET_FILE="${TARGET_DIR}/agent.env"
PREFIX="/uzex/prod"

install -d -m 0700 -o root -g root "$TARGET_DIR"
umask 077
TMP="$(mktemp "${TARGET_DIR}/agent.env.XXXXXX")"
# Always remove the temp file if we fail before the atomic move.
trap 'rm -f "$TMP"' EXIT

read_secret() {
  # $1 = SSM parameter name (without prefix)
  local name="$1"
  local value
  if ! value="$(aws ssm get-parameter \
      --region "$REGION" \
      --name "${PREFIX}/${name}" \
      --with-decryption \
      --query 'Parameter.Value' \
      --output text 2>/dev/null)"; then
    echo "ERROR: cannot read SSM parameter ${PREFIX}/${name}" >&2
    exit 1
  fi
  if [[ -z "$value" || "$value" == "None" ]]; then
    echo "ERROR: SSM parameter ${PREFIX}/${name} is empty" >&2
    exit 1
  fi
  printf '%s' "$value"
}

read_plain() {
  # Non-secret configuration. A missing value falls back to the default.
  local name="$1"
  local default="${2:-}"
  local value
  value="$(aws ssm get-parameter \
      --region "$REGION" \
      --name "${PREFIX}/${name}" \
      --query 'Parameter.Value' \
      --output text 2>/dev/null || true)"
  if [[ -z "$value" || "$value" == "None" ]]; then
    value="$default"
  fi
  printf '%s' "$value"
}

# --- Database ---
POSTGRES_DB="$(read_plain postgres_db uzex)"
POSTGRES_PASSWORD="$(read_secret postgres_password)"
UZEX_READER_PASSWORD="$(read_secret reader_password)"
APP_SECRET="$(read_secret app_secret)"

# --- Groq primary and same-scope redundancy ---
GROQ_API_KEY="$(read_secret groq_api_key)"
GROQ_API_KEY_SECONDARY="$(read_secret groq_api_key_secondary)"
GROQ_API_KEY_SECONDARY_SAME_ORG="$(read_secret groq_api_key_secondary_same_org)"
GROQ_API_KEY_TERTIARY_SAME_ORG="$(read_secret groq_api_key_tertiary_same_org)"
GROQ_ORGANIZATION_SCOPE_ID="$(read_plain groq_organization_scope_id '')"
GROQ_PROJECT_SCOPE_ID="$(read_plain groq_project_scope_id '')"
if [[ -z "$GROQ_ORGANIZATION_SCOPE_ID" || -z "$GROQ_PROJECT_SCOPE_ID" ]]; then
  echo "ERROR: real Groq organization/project scope IDs are required; placeholders are not accepted" >&2
  exit 1
fi
case "$GROQ_ORGANIZATION_SCOPE_ID" in
  groq-default-org|REPLACE_WITH_REAL_GROQ_ORG_ID)
    echo "ERROR: GROQ_ORGANIZATION_SCOPE_ID is still a placeholder" >&2
    exit 1
    ;;
esac
case "$GROQ_PROJECT_SCOPE_ID" in
  groq-default-project|REPLACE_WITH_REAL_GROQ_PROJECT_ID)
    echo "ERROR: GROQ_PROJECT_SCOPE_ID is still a placeholder" >&2
    exit 1
    ;;
esac

# --- Safe non-secret defaults ---
PLANNER_MODE="$(read_plain planner_mode llm)"
WEB_PORT="$(read_plain web_port 8080)"
CORS_ORIGINS="$(read_plain cors_origins '')"
DATASET_CUTOFF_DATE="$(read_plain dataset_cutoff_date 2026-10-30)"
LLM_FALLBACK_CHAIN="$(read_plain llm_fallback_chain '')"
LLM_PLAN_CRITIC_MODE="$(read_plain llm_plan_critic_mode off)"
LLM_RAG_ENABLED="$(read_plain llm_rag_enabled false)"

{
  echo "# Generated by deploy/aws/render-env.sh from SSM ${PREFIX}/*"
  echo "# Mode 0600, owner root. Never copy this file into an image or repository."
  echo "POSTGRES_DB=${POSTGRES_DB}"
  echo "POSTGRES_PASSWORD=${POSTGRES_PASSWORD}"
  echo "UZEX_READER_PASSWORD=${UZEX_READER_PASSWORD}"
  echo "APP_SECRET=${APP_SECRET}"
  echo "PLANNER_MODE=${PLANNER_MODE}"
  echo "WEB_PORT=${WEB_PORT}"
  echo "DATASET_CUTOFF_DATE=${DATASET_CUTOFF_DATE}"
  echo "CORS_ORIGINS=${CORS_ORIGINS}"
  echo
  echo "LLM_PROVIDER=groq"
  echo "LLM_PRIMARY_PROVIDER=groq"
  echo "LLM_PRIMARY_MODEL=openai/gpt-oss-120b"
  echo "GROQ_BASE_URL=https://api.groq.com/openai/v1"
  echo "GROQ_MODEL=openai/gpt-oss-120b"
  echo "GROQ_API_KEY=${GROQ_API_KEY}"
  echo "GROQ_API_KEY_SECONDARY=${GROQ_API_KEY_SECONDARY}"
  echo "GROQ_API_KEY_SECONDARY_SAME_ORG=${GROQ_API_KEY_SECONDARY_SAME_ORG}"
  echo "GROQ_API_KEY_TERTIARY_SAME_ORG=${GROQ_API_KEY_TERTIARY_SAME_ORG}"
  echo "GROQ_ORGANIZATION_SCOPE_ID=${GROQ_ORGANIZATION_SCOPE_ID}"
  echo "GROQ_PROJECT_SCOPE_ID=${GROQ_PROJECT_SCOPE_ID}"
  echo
  echo "LLM_FALLBACK_ENABLED=true"
  echo "LLM_FALLBACK_CHAIN=${LLM_FALLBACK_CHAIN}"
  echo "LLM_QUALIFICATION_REQUIRED=true"
  echo "LLM_PLAN_CRITIC_MODE=${LLM_PLAN_CRITIC_MODE}"
  echo "LLM_RAG_ENABLED=${LLM_RAG_ENABLED}"
} > "$TMP"

chown root:root "$TMP"
chmod 0600 "$TMP"
mv -f "$TMP" "$TARGET_FILE"
trap - EXIT

echo "Wrote ${TARGET_FILE} (mode 0600). Values were not printed."
echo "Next:"
echo "  cd /opt/uzex"
echo "  sudo docker compose --env-file ${TARGET_FILE} build"
echo "  sudo docker compose --env-file ${TARGET_FILE} up -d"
